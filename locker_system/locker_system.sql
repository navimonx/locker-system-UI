CREATE DATABASE IF NOT EXISTS `locker_system`
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `locker_system`;

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- ---------------------------------------------------------------------
--  Users  (students and admins)
--  Admin logins use an email in `studentId`; students use XX-XXXX.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `Users` (
  `id`         INT          NOT NULL AUTO_INCREMENT,
  `studentId`  VARCHAR(120) NOT NULL,
  `lastName`   VARCHAR(50)  NOT NULL,
  `middleName` VARCHAR(50)  NULL,
  `firstName`  VARCHAR(50)  NOT NULL,
  `password`   VARCHAR(255) NOT NULL DEFAULT '',
  `role`       VARCHAR(10)  NOT NULL DEFAULT 'student',
  `course`     VARCHAR(150) NULL,
  `contact`    VARCHAR(30)  NULL,
  `email`      VARCHAR(120) NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `UQ_Users_studentId` (`studentId`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
--  Lockers  (6 colleges x 6 floors x 20 lockers)
--  `slot` is the locker's position (1-20) on its floor.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `Lockers` (
  `id`         INT         NOT NULL AUTO_INCREMENT,
  `department` VARCHAR(20) NOT NULL,
  `floor`      INT         NOT NULL,
  `slot`       INT         NOT NULL,
  `status`     VARCHAR(20) NOT NULL DEFAULT 'available',
  `owner_id`   INT         NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `UQ_Lockers_position` (`department`, `floor`, `slot`),
  KEY `IX_Lockers_owner` (`owner_id`),
  CONSTRAINT `FK_Lockers_owner` FOREIGN KEY (`owner_id`) REFERENCES `Users` (`id`) ON DELETE SET NULL,
  CONSTRAINT `CK_Lockers_status` CHECK (`status` IN ('available', 'pending', 'occupied'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
--  Reservations
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `Reservations` (
  `id`                 INT          NOT NULL AUTO_INCREMENT,
  `user_id`            INT          NOT NULL,
  `locker_id`          INT          NOT NULL,
  `status`             VARCHAR(20)  NOT NULL DEFAULT 'pending',
  `duration`           VARCHAR(50)  NULL,
  `reserved_at`        DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `ends_at`            DATETIME     NULL,
  `expiry_notified_at` DATETIME     NULL,
  `released_at`        DATETIME     NULL,
  `course`             VARCHAR(150) NULL,
  `yearLevel`          VARCHAR(20)  NULL,
  `contact`            VARCHAR(120) NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `UQ_LockerUser` (`user_id`, `locker_id`),
  KEY `IX_Reservations_locker_status` (`locker_id`, `status`),
  KEY `IX_Reservations_status_ends` (`status`, `ends_at`),
  CONSTRAINT `FK_Reservations_user`   FOREIGN KEY (`user_id`)   REFERENCES `Users`   (`id`) ON DELETE CASCADE,
  CONSTRAINT `FK_Reservations_locker` FOREIGN KEY (`locker_id`) REFERENCES `Lockers` (`id`),
  CONSTRAINT `CK_Reservations_status` CHECK (`status` IN
    ('pending', 'approved', 'rejected', 'released', 'expired', 'cancelled', 'deleted'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
--  Approved student numbers (the sign-up whitelist managed by admins)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `AllowedStudentIds` (
  `id`         INT         NOT NULL AUTO_INCREMENT,
  `studentId`  VARCHAR(10) NOT NULL,
  `added_at`   DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `added_by`   INT         NULL,
  `claimed_at` DATETIME    NULL,
  `user_id`    INT         NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `UQ_AllowedStudentIds_studentId` (`studentId`),
  KEY `IX_AllowedStudentIds_unclaimed` (`claimed_at`, `studentId`),
  CONSTRAINT `FK_AllowedStudentIds_added_by` FOREIGN KEY (`added_by`) REFERENCES `Users` (`id`) ON DELETE SET NULL,
  CONSTRAINT `FK_AllowedStudentIds_user_id`  FOREIGN KEY (`user_id`)  REFERENCES `Users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SET FOREIGN_KEY_CHECKS = 1;

